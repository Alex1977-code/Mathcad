import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

/**
 * Offline support: after the build a service worker (dist/sw.js) is written that precaches every built
 * file (app, calculation worker, fonts, lazily loaded importers/exporters). The cache name contains a hash
 * of all files, so a new build replaces the old cache as a whole.
 */
function offlinePlugin(): Plugin {
  let outDir = 'dist';
  return {
    name: 'formelwerk-offline',
    apply: 'build',
    configResolved(c) { outDir = c.build.outDir; },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const f of readdirSync(dir)) {
          const p = join(dir, f);
          if (statSync(p).isDirectory()) walk(p);
          else files.push(relative(outDir, p).replace(/\\/g, '/'));
        }
      };
      try { walk(outDir); } catch { return; }
      // old font formats are only fallbacks for browsers that cannot run the app anyway: not precached
      const list = files.filter(f => f !== 'sw.js' && !f.endsWith('.map') && !/KaTeX_[^/]*\.(ttf|woff)$/.test(f)).sort();
      const hash = createHash('sha256');
      for (const f of list) { hash.update(f); hash.update(readFileSync(join(outDir, f))); }
      const version = hash.digest('hex').slice(0, 12);
      const urls = ['./', ...list.filter(f => f !== 'index.html').map(f => './' + f)];
      writeFileSync(join(outDir, 'sw.js'), SW_SOURCE.replace('__VERSION__', version).replace('__FILES__', JSON.stringify(urls)));
    },
  };
}

const SW_SOURCE = `/* FormelWerk – offline cache (generated by the build) */
const CACHE = 'formelwerk-__VERSION__';
const FILES = __FILES__;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((u) => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('formelwerk-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

// the page asks the waiting worker to take over (after "Neu laden")
self.addEventListener('message', (event) => { if (event.data === 'skipWaiting') self.skipWaiting(); });

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // the app itself for every navigation; files from the cache, the network only as a fallback
    // (ignoreVary: servers answer with "Vary: Origin"; the cached copy must still serve script requests)
    const hit = req.mode === 'navigate' ? await cache.match('./', { ignoreVary: true }) : await cache.match(req, { ignoreSearch: true, ignoreVary: true });
    if (hit) return hit;
    try { return await fetch(req); } catch (e) {
      const shell = req.mode === 'navigate' ? await cache.match('./', { ignoreVary: true }) : undefined;
      if (shell) return shell;
      throw e;
    }
  })());
});
`;

export default defineConfig({
  base: './',
  plugins: [react(), offlinePlugin()],
  build: { chunkSizeWarningLimit: 2000 },
  worker: { format: 'es' },
  test: {
    environment: 'node',
    include: ['tests/**/*.test.ts'],
    testTimeout: 60000,
  },
} as any);
